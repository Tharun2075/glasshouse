// Self-host Inter Variable and JetBrains Mono Variable (OFL-1.1, @fontsource-variable) from public/fonts.
// Copies the latin + latin-ext woff2 files and writes app/fonts.css. Run after bumping the font packages: node scripts/build-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const sets = [["inter", "wght.css"], ["inter", "wght-italic.css"], ["jetbrains-mono", "wght.css"]];
const keep = /-(latin|latin-ext)-wght-(normal|italic)\.woff2/;
mkdirSync("public/fonts", { recursive: true });
let css = "/* GENERATED by scripts/build-fonts.mjs from @fontsource-variable (OFL-1.1); latin + latin-ext only. */\n";
for (const [pkg, file] of sets) {
  const dir = join("node_modules/@fontsource-variable", pkg);
  for (const face of readFileSync(join(dir, file), "utf8").split(/(?=\/\*)/)) {
    const m = face.match(/url\(\.\/files\/([^)]+)\)/);
    if (!m || !keep.test(m[1])) continue;
    copyFileSync(join(dir, "files", m[1]), join("public/fonts", m[1]));
    css += face.replace(`./files/${m[1]}`, `/fonts/${m[1]}`).trim() + "\n";
  }
}
for (const pkg of ["inter", "jetbrains-mono"]) copyFileSync(join("node_modules/@fontsource-variable", pkg, "LICENSE"), join("public/fonts", `${pkg}-LICENSE.txt`));
writeFileSync("app/fonts.css", css);
console.log("build-fonts: wrote app/fonts.css and public/fonts");
